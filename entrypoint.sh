#!/bin/sh
# ============================================
# Entrypoint script для Индустриальный гид
# Автоматически инициализирует БД при первом запуске
# ============================================

set -e

echo "========================================"
echo "Индустриальный гид - Запуск..."
echo "========================================"

WORKDIR="/app"

# Проверяем, существует ли уже база данных
if [ ! -f "$DB_PATH" ]; then
	echo "[INIT] База данных не найдена. Создаю структуру..."
	cd $WORKDIR && node server/src/db/db.js init
	echo "[INIT] Загружаю демо-данные..."
	cd $WORKDIR && node server/src/db/seed.js
	echo "[INIT] Готово!"
else
	echo "[INIT] База данных уже существует. Пропускаю инициализацию."
fi

# Проверяем существование директории uploads
if [ ! -d "/app/uploads" ]; then
	echo "[INIT] Создаю директорию uploads..."
	mkdir -p /app/uploads/covers /app/uploads/logos
fi

echo "========================================"
echo "Запуск приложения..."
echo "========================================"

cd $WORKDIR
exec "$@"